use super::*;
use crate::nats_worker::result_fixture::binary;
use async_nats::{Client, Message, Subscriber};
use futures_util::StreamExt;
use harnx_core::child_process::ChildProcessManager;
use harnx_toolset::{
    server_identity_token, ToolRequest, HARNX_SERVER_CONFIG, HARNX_SERVER_PACKAGE,
};
use harnx_toolset_server::{
    invocation_journal::InvocationJournal, registration_key, TOOL_REGISTRY_BUCKET,
};
use tokio::process::{Child, Command};

pub(super) struct NativeToolset<'a> {
    env: &'a ResultEnvironment,
    source: &'a Source,
    pub exposed_tool: &'static str,
    executable: &'static str,
    identity: String,
    subject: String,
    children: ChildProcessManager,
}

impl<'a> NativeToolset<'a> {
    pub fn new(env: &'a ResultEnvironment, source: &'a Source) -> Self {
        let (server, tool, exposed_tool, executable) = match source {
            Source::Fetch(_) => (
                "fetch",
                "fetch_markdown",
                "fetch_fetch_markdown",
                "harnx-fetch-tools",
            ),
            Source::Fs(_) => ("fs", "read", "fs_read", "harnx-fs-tools"),
        };
        let identity = server_identity_token(None, "", server);
        Self {
            env,
            source,
            exposed_tool,
            executable,
            subject: env.scope.tool_subject(&identity, tool),
            identity,
            children: ChildProcessManager::new(),
        }
    }

    pub fn client(&self) -> Client {
        self.env.js.client()
    }

    pub async fn start(&self) -> Result<Child> {
        let key = registration_key(&self.env.scope, &self.identity);
        let previous = self.registration_revision(&key).await?;
        let mut child = self.children.spawn(self.command()?).await?;
        // The stopped process can leave a valid registration until its TTL.
        // Wait for a write by the new process, after it subscribes to requests.
        poll_until(async || {
            if let Some(status) = child.try_wait()? {
                anyhow::bail!("{} exited during startup: {status}", self.executable);
            }
            Ok(self.registration_revision(&key).await? > previous)
        })
        .await?;
        Ok(child)
    }

    async fn registration_revision(&self, key: &str) -> Result<u64> {
        let Ok(registry) = self.env.js.get_key_value(TOOL_REGISTRY_BUCKET).await else {
            return Ok(0);
        };
        Ok(registry.entry(key).await?.map_or(0, |entry| entry.revision))
    }

    fn command(&self) -> Result<Command> {
        let mut command = Command::new(binary(self.executable)?);
        command
            .env("HARNX_SERVER_SCOPE", self.env.scope.as_str())
            .env("HARNX_NATS_URL", self.env.broker.url())
            .env_remove("HARNX_NATS_TOKEN")
            .env_remove(HARNX_SERVER_PACKAGE)
            .env_remove(HARNX_SERVER_CONFIG)
            .kill_on_drop(true);
        match self.source {
            Source::Fetch(_) => command.arg("--allow-private-ip"),
            Source::Fs(dir) => command.arg("--allow-read").arg(dir.path()),
        };
        Ok(command)
    }

    pub async fn redeliver(&self, call: &ObservedCall) -> Result<Message> {
        let journal = InvocationJournal::ensure(&self.env.js, 1).await?;
        let committed = journal
            .get(&call.request)
            .await?
            .and_then(|row| row.reply)
            .context("native reply was not committed")?;
        assert_eq!(serde_json::to_vec(&committed)?, call.reply);
        let headers = call
            .message
            .headers
            .clone()
            .context("worker invocation headers")?;
        Ok(self
            .client()
            .send_request(
                self.subject.clone(),
                async_nats::Request::new()
                    .headers(headers)
                    .payload(call.message.payload.clone())
                    .timeout(Some(CI_SAFE_TIMEOUT)),
            )
            .await?)
    }
}

pub(super) struct ObservedCall {
    pub request: ToolRequest,
    pub reply: bytes::Bytes,
    message: Message,
}

pub(super) struct WireTap {
    requests: Subscriber,
    replies: Subscriber,
}

impl WireTap {
    pub async fn subscribe(toolset: &NativeToolset<'_>) -> Result<Self> {
        let client = toolset.client();
        let requests = client.subscribe(toolset.subject.clone()).await?;
        // Worker request inboxes are generated by async-nats. On this isolated
        // broker, tap inbox traffic and match replies to their request subject.
        let replies = client.subscribe("_INBOX.>").await?;
        client.flush().await?;
        Ok(Self { requests, replies })
    }

    pub async fn calls(self) -> Result<[ObservedCall; 2]> {
        tokio::time::timeout(CI_SAFE_TIMEOUT, self.collect())
            .await
            .context("missing native tool requests or replies")?
    }

    async fn collect(mut self) -> Result<[ObservedCall; 2]> {
        let first = self.requests.next().await.context("first request")?;
        let second = self.requests.next().await.context("second request")?;
        let mut replies = [None, None];
        while let Some(reply) = self.replies.next().await {
            if first.reply.as_ref() == Some(&reply.subject) {
                replies[0] = Some(reply.payload);
            } else if second.reply.as_ref() == Some(&reply.subject) {
                replies[1] = Some(reply.payload);
            }
            if let [Some(first_reply), Some(second_reply)] = &replies {
                return Ok([
                    ObservedCall::new(first, first_reply.clone())?,
                    ObservedCall::new(second, second_reply.clone())?,
                ]);
            }
        }
        anyhow::bail!("reply tap closed")
    }
}

impl ObservedCall {
    fn new(message: Message, reply: bytes::Bytes) -> Result<Self> {
        Ok(Self {
            request: serde_json::from_slice(&message.payload)?,
            reply,
            message,
        })
    }
}
